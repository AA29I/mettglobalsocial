export function isBestTimeNetwork(platform: string): platform is BestTimeNetwork {
  return (bestTimeNetworks as readonly string[]).includes(platform);
}

export function getBestTimeScore(
  network: string,
  dayIndex: number,
  hour: number,
): number {
  const key: BestTimeNetwork = isBestTimeNetwork(network)
    ? network
    : "instagram";
  const dayRow = bestTimesByNetwork[key][dayIndex];
  if (!dayRow) return 0;
  return dayRow[hour] ?? 0;
}

export type HeatShading = {
  score: number;
  level: 0 | 1 | 2 | 3 | 4;
  label: string;
  backgroundColor: string;
};

/**
 * Maps an hourly score (0–100) to blue heat shading (darker means better).
 */
export function getBestTimeShading(score: number): HeatShading {
  const clamped = Math.max(0, Math.min(100, score));
  const level: 0 | 1 | 2 | 3 | 4 =
    clamped >= 80
      ? 4
      : clamped >= 60
        ? 3
        : clamped >= 40
          ? 2
          : clamped >= 20
            ? 1
            : 0;
  const labels = ["Quiet", "Low", "Moderate", "Good", "Best time"] as const;
  // Smooth blue heat scale: higher score -> darker, richer blue shading
  const alpha = Number((0.04 + (clamped / 100) * 0.64).toFixed(3));
  const r = Math.round(37 - (clamped / 100) * 20);
  const g = Math.round(108 - (clamped / 100) * 48);
  const b = Math.round(235 - (clamped / 100) * 55);
  return {
    score: clamped,
    level,
    label: labels[level],
    backgroundColor: `rgba(${r}, ${g}, ${b}, ${alpha})`,
  };
}
